interface ResearchArgs {
  itemIds: string[];
  agent?: string;
  template?: string;
  digest?: boolean;
  help?: boolean;
  /** Batch mode (#189 / ADR-0014): research every detected item matching filters. */
  batch?: boolean;
  /** Restrict batch mode to items with this status (default: `detected`). */
  status?: string;
  /** Hard-cap on items processed in batch mode (default: RESEARCH_BATCH_DEFAULT_MAX_ITEMS). */
  maxItems?: string;
  /** Comma-separated allow-list matched against each item's `matchedKeywords`. */
  filterTags?: string;
  /**
   * Digest-mode slug override (#255 / ADR-0018 §W-H): the `triage.group` key
   * the digest belongs to. When set, the digest filename is derived from this
   * group instead of `matchedKeywords` frequency, so a single-keyword source
   * that emits 2+ groups on the same cron tick no longer collides on
   * `<date>_digest_<slug>_v1.md`. Falls back to the matchedKeywords slug when
   * omitted (back-compat).
   */
  triageGroup?: string;
  /**
   * Host-agent mode (#254 / ADR-0019): emit the research payload to stdout
   * without spawning an agent. The host (interactive) session executes the
   * SKILL procedure itself, then finalizes via `--commit`.
   */
  emitPayload?: boolean;
  /**
   * Host-agent mode (#254 / ADR-0019): finalize an externally-written report.
   * Holds the path to the report the host session wrote. The CLI validates it
   * against `ResearchFrontmatterSchema` and applies the status transition.
   */
  commit?: string;
}

function parseArgs(args: string[]): ResearchArgs {
  const out: ResearchArgs = { itemIds: [] };
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === "-h" || a === "--help") {
      out.help = true;
      continue;
    }
    if (a === "--digest") {
      out.digest = true;
      continue;
    }
    if (a === "--batch") {
      out.batch = true;
      continue;
    }
    if (a === "--agent") {
      out.agent = args[++i];
      continue;
    }
    if (a === "--template") {
      out.template = args[++i];
      continue;
    }
    if (a === "--status") {
      out.status = args[++i];
      continue;
    }
    if (a === "--max-items") {
      out.maxItems = args[++i];
      continue;
    }
    if (a === "--filter-tags") {
      out.filterTags = args[++i];
      continue;
    }
    if (a === "--triage-group") {
      out.triageGroup = args[++i];
      continue;
    }
    if (a === "--emit-payload") {
      out.emitPayload = true;
      continue;
    }
    if (a === "--commit") {
      out.commit = args[++i];
      continue;
    }
    if (a?.startsWith("--")) {
      throw new Error(`unknown option: ${a}`);
    }
    if (a !== undefined) {
      out.itemIds.push(a);
    }
  }
  return out;
}

